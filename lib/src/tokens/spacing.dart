/// Bootstrap Italia spacing scale.
///
/// Based on Bootstrap's spacing utilities where 1rem = 16px.
abstract final class BootstrapItaliaSpacing {
  /// No spacing. 0px.
  static const double space0 = 0;

  /// Extra small spacing. 4px (0.25rem).
  static const double space1 = 4;

  /// Small spacing. 8px (0.5rem).
  static const double space2 = 8;

  /// Medium spacing. 16px (1rem). Base unit.
  static const double space3 = 16;

  /// Large spacing. 24px (1.5rem).
  static const double space4 = 24;

  /// Extra large spacing. 48px (3rem).
  static const double space5 = 48;
}
